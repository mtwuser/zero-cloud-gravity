def _fmt_codeowner_group(emails: tuple[str, ...], fallback: str) -> str:
    return " ".join(dict.fromkeys(e for e in emails if "@" in e and "*" not in e)) or fallback


def configure_git_governance_policy(
    target_dir: Path, *, protected_branches: list[str] | None = None,
    require_pr_on_protected: bool = True, sync_codeowners: bool = True, dry_run: bool = False,
) -> dict[str, Any]:  # fmt: skip
    """Configure persistent Git branch/environment rules and optional .github/CODEOWNERS."""
    ws, mpath = target_dir.resolve(), target_dir.resolve() / NODE_MANIFEST_REL_PATH
    if not mpath.is_file():
        raise ValueError(f"Missing node manifest: {mpath}")
    manifest = load_node_manifest(ws)
    layer_id = str(manifest.get("layer_id", ws.name))
    is_ind = (
        manifest.get("entity_kind") == "individual"
        or int(manifest.get("precedence", 50)) >= INDIVIDUAL_MIN_PRECEDENCE
    )
    p_pipe = "direct" if is_ind else "staged"
    def_prot = ("main", "master") if is_ind else DEFAULT_PROTECTED_BRANCHES
    prot = [b.strip() for b in (protected_branches or def_prot) if b.strip()]
    env_map = {"dev": "feature/*", "pro": "master"} if is_ind else dict(DEFAULT_ENV_BRANCH_MAP)
    env_ord = ["dev", "pro"] if is_ind else list(VALID_ENVIRONMENTS)
    git_gov: dict[str, Any] = {
        "promotion_pipeline": p_pipe, "protected_branches": prot,
        "protected_specialty_prefix": "specialty/",
        "context_branch_prefixes": dict(DEFAULT_CONTEXT_BRANCH_PREFIXES),
        "process_branch_prefixes": dict(DEFAULT_PROCESS_BRANCH_PREFIXES),
        "governance_pr_prefixes": dict(DEFAULT_GOVERNANCE_PR_PREFIXES),
        "capsule_ref_namespace": CAPSULE_REF_NAMESPACE,
        "require_pr_on_protected": require_pr_on_protected,
        "environment_branches": env_map, "environment_promotion_order": env_ord,
    }  # fmt: skip
    manifest["git_governance"] = git_gov
    raw_auth = manifest.get("layer_authority")
    auth: dict[str, Any] = raw_auth if isinstance(raw_auth, dict) else {}
    emails = tuple(str(e).strip() for e in auth.get("authorized_emails", []) if str(e).strip())
    maint_ems = tuple(str(e).strip() for e in auth.get("maintainer_emails", []) if str(e).strip())
    val_ems = tuple(str(e).strip() for e in auth.get("validator_emails", []) if str(e).strip())
    owners_str = _fmt_codeowner_group(emails, "@layer-owners")
    maint_str = _fmt_codeowner_group((*emails, *maint_ems), owners_str)
    val_str = _fmt_codeowner_group((*emails, *maint_ems, *val_ems), maint_str)
    codeowners_rel = ".github/CODEOWNERS"
    codeowners_content = (
        f"# Auto-generated by ZeroCloudGravity zcg configure-git-policy ({layer_id})\n"
        f"/{NODE_MANIFEST_REL_PATH} {owners_str}\n/templates/ {maint_str}\n"
        f"/.agents/rules/layer-* {owners_str}\n/corporate/ {owners_str}\n"
        f"/WORKROAD.md {maint_str}\n/ROADMAP.md {maint_str}\n/WORKVALI.md {val_str}\n"
    )
    if not dry_run:
        mpath.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", "utf-8")
        if sync_codeowners:
            co_file = ws / codeowners_rel
            co_file.parent.mkdir(parents=True, exist_ok=True)
            co_file.write_text(codeowners_content, encoding="utf-8")
    return {
        "target_dir": str(ws), "layer_id": layer_id, "dry_run": dry_run,
        "git_governance": git_gov, "codeowners_owners": owners_str,
        "codeowners_file": codeowners_rel if sync_codeowners else None,
    }  # fmt: skip


def manage_layer_roster(
    target_dir: Path, *, add_email: str | None = None, member_role: str = "member",
    title: str = "", squad: str = "", remove_email: str | None = None, dry_run: bool = False,
) -> dict[str, Any]:  # fmt: skip
    """Maintain node RBAC roster (owners, maintainers, validators, members) and CODEOWNERS."""
    ws, mpath = target_dir.resolve(), target_dir.resolve() / NODE_MANIFEST_REL_PATH
    clean_role = member_role.strip().lower()
    if not mpath.is_file():
        raise ValueError(f"Missing node manifest: {mpath}")
    if clean_role not in VALID_ROSTER_ROLES:
        raise ValueError(f"Invalid member_role {member_role!r}: must be in {VALID_ROSTER_ROLES}")
    manifest = load_node_manifest(ws)
    layer_id = str(manifest.get("layer_id", ws.name))
    raw_auth = manifest.get("layer_authority")
    auth: dict[str, Any] = dict(raw_auth) if isinstance(raw_auth, dict) else {}
    raw_rval = auth.get("roster")
    raw_roster: dict[str, Any] = raw_rval if isinstance(raw_rval, dict) else {}
    r_keys = ("owners", "maintainers", "validators", "members")
    roster: dict[str, list[dict[str, str]]] = {
        k: [dict(x) for x in raw_roster.get(k, []) if isinstance(x, dict)] for k in r_keys
    }
    for em_arg, do_add in ((remove_email, False), (add_email, True)):
        for raw_em in (em_arg or "").split(","):
            if clean_em := raw_em.strip():
                em_low = clean_em.lower()
                for k in r_keys:
                    roster[k] = [m for m in roster[k] if m.get("email", "").lower() != em_low]
                if do_add:
                    entry = {
                        "email": clean_em, "title": title.strip() or clean_role,
                        "squad": squad.strip(),
                    }  # fmt: skip
                    roster[f"{clean_role}s"].append(entry)
                else:
                    for ek in ("authorized_emails", "maintainer_emails", "validator_emails"):
                        auth[ek] = [e for e in auth.get(ek, []) if str(e).lower() != em_low]
    owner_ems = [m["email"] for m in roster["owners"] if m.get("email")]
    maint_ems = [m["email"] for m in roster["maintainers"] if m.get("email")]
    val_ems = [m["email"] for m in roster["validators"] if m.get("email")]
    cur_auth = [str(e).strip() for e in auth.get("authorized_emails", []) if str(e).strip()]
    new_auth = {
        **auth, "roster": roster,
        "authorized_emails": list(dict.fromkeys([*cur_auth, *owner_ems])),
        "maintainer_emails": list(dict.fromkeys(maint_ems)),
        "validator_emails": list(dict.fromkeys(val_ems)),
    }  # fmt: skip
    manifest["layer_authority"] = new_auth
    if not dry_run:
        mpath.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", "utf-8")
        if (ws / ".github/CODEOWNERS").is_file() or add_email or remove_email:
            configure_git_governance_policy(ws, sync_codeowners=True, dry_run=False)
    return {
        "target_dir": str(ws), "layer_id": layer_id, "roster": roster, "dry_run": dry_run,
        "authorized_emails": new_auth["authorized_emails"],
        "maintainer_emails": new_auth["maintainer_emails"],
        "validator_emails": new_auth["validator_emails"],
    }  # fmt: skip


def inspect_git_governance_state(
    workspace_dir: Path, *, current_branch: str | None = None
) -> dict[str, Any]:
    """Inspect active Git branch, inferred process stage, environment, and governance alerts."""
    ws, manifest = workspace_dir.resolve(), load_node_manifest(workspace_dir.resolve())
    raw_gg = manifest.get("git_governance")
    gg: dict[str, Any] = raw_gg if isinstance(raw_gg, dict) else {}
    role = str(manifest.get("layer_role", "project"))
    is_ind = (
        manifest.get("entity_kind") == "individual"
        or int(manifest.get("precedence", 50)) >= INDIVIDUAL_MIN_PRECEDENCE
    )
    raw_pipe = str(gg.get("promotion_pipeline") or "")
    def_pipe = "direct" if is_ind else "staged"
    p_pipe = raw_pipe if raw_pipe in VALID_PROMOTION_PIPELINES else def_pipe
    def_prot = ("main", "master") if is_ind else DEFAULT_PROTECTED_BRANCHES
    prot = [str(b) for b in gg.get("protected_branches", def_prot)]
    raw_pfx = gg.get("process_branch_prefixes")
    pfx_extra: dict[str, Any] = raw_pfx if isinstance(raw_pfx, dict) else {}
    prefixes = {**DEFAULT_PROCESS_BRANCH_PREFIXES, **pfx_extra}
    branch = (current_branch or "").strip()
    if not branch and (ws / ".git").exists():
        git_bin = shutil.which("git") or "/usr/bin/git"
        proc = subprocess.run(  # noqa: S603
            [git_bin, "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=ws, check=False, capture_output=True, text=True,
        )  # fmt: skip
        branch = proc.stdout.strip()
    eff_branch = branch or "main"
    on_trunk = eff_branch in ("main", "master")
    is_spec = eff_branch.startswith("specialty/")
    is_pers = eff_branch.startswith(("hat/", "machine/"))
    is_gov_pr = any(eff_branch.startswith(p) for p in DEFAULT_GOVERNANCE_PR_PREFIXES.values())
    is_proc = any(eff_branch.startswith(str(p)) for p in prefixes.values())
    branch_cat = (
        "protected-trunk-or-env" if eff_branch in prot else (
            "specialty-lens" if is_spec else (
                "personal-workstation" if is_pers else (
                    "governance-pr" if is_gov_pr else ("tactical-process" if is_proc else "custom")
                )
            )
        )
    )  # fmt: skip
    stage = next(
        (str(st) for st, pfx in prefixes.items() if eff_branch.startswith(str(pfx))),
        "protected-main" if on_trunk else "environment-branch",
    )
    is_pro = on_trunk or eff_branch == "env/pro" or eff_branch.startswith("release/v")
    active_env = (
        "pro" if is_pro else (
            "pre" if eff_branch.startswith(("env/pre", "pre/")) else (
                "tst" if eff_branch.startswith(("env/tst", "tst/")) else "dev"
            )
        )
    )  # fmt: skip
    audit_file = ws / "logs" / "governance_audit.jsonl"
    raw_lines = (
        audit_file.read_text("utf-8").splitlines()[-AUDIT_LOG_TAIL_LINES:]
        if audit_file.is_file()
        else []
    )
    alerts = [item for line in raw_lines if (item := json.loads(line)).get("status") != "allowed"]
    proposals_dir = ws / ".agents" / "proposals"
    p_paths = sorted(proposals_dir.rglob("*.md")) if proposals_dir.is_dir() else []
    staged_files = [str(p.relative_to(ws)).replace("\\", "/") for p in p_paths]
    now_ts = datetime.now(UTC).timestamp()
    stale_props = [
        str(p.relative_to(ws)).replace("\\", "/")
        for p in p_paths
        if (now_ts - p.stat().st_mtime) / SECONDS_PER_DAY > STALE_PROPOSAL_MAX_DAYS
    ]
    redir_cmd = (
        None
        if on_trunk
        else (
            f"git checkout master && make sync && git checkout {eff_branch} "
            "&& git merge --no-edit master"
        )
    )
    trunk_pol = "direct-on-trunk" if on_trunk else f"redirect-to-trunk-then-merge:{eff_branch}"
    return {
        "current_branch": eff_branch, "branch_category": branch_cat, "promotion_pipeline": p_pipe,
        "context_branch_prefixes": dict(DEFAULT_CONTEXT_BRANCH_PREFIXES),
        "reconciliation_guard": {
            "on_trunk_branch": on_trunk, "trunk_update_policy": trunk_pol,
            "redirection_command": redir_cmd,
        },
        "is_protected_branch": eff_branch in prot or is_spec, "active_process_stage": stage,
        "active_environment": active_env, "protected_branches": prot,
        "capsule_ref_namespace": CAPSULE_REF_NAMESPACE,
        "codeowners_synced": (ws / ".github" / "CODEOWNERS").is_file(),
        "makefile_outdated": is_makefile_outdated(ws, role),
        "manifest_contracts_outdated": bool(
            manifest and manifest.get("schema_version") != NODE_MANIFEST_CONTRACT_REV
        ),
        "staged_proposals": staged_files, "stale_proposals": stale_props,
        "staleness_thresholds_days": {
            "proposals": STALE_PROPOSAL_MAX_DAYS,
            "modules_and_specs": STALE_MODULE_REVIEW_DAYS,
            "policies": STALE_POLICY_REVIEW_DAYS,
        },
        "recent_governance_alerts": alerts[-MAX_RECENT_GOVERNANCE_ALERTS:],
    }  # fmt: skip


def record_governance_decision(
    workspace_dir: Path, *, item_ref: str, decision: str, reason: str,
    actor_email: str = "", tracker: str = "WORKTASK.md", dry_run: bool = False,
) -> dict[str, Any]:  # fmt: skip
    """Record a human governance review decision (approve, reject, defer, blocked) in tracker."""
    clean_dec, clean_ref, clean_reason = decision.strip().lower(), item_ref.strip(), reason.strip()
    if clean_dec not in VALID_GOVERNANCE_DECISIONS:
        raise ValueError(f"Invalid decision {decision!r}: must be in {VALID_GOVERNANCE_DECISIONS}")
    if not clean_ref or not clean_reason:
        raise ValueError("Both item_ref and reason must be non-empty strings")
    ws, manifest = workspace_dir.resolve(), load_node_manifest(workspace_dir.resolve())
    lid = str(manifest.get("layer_id", ws.name))
    status_map = {
        "approve": "approved", "reject": "rejected", "defer": "deferred", "blocked": "blocked"
    }  # fmt: skip
    mapped_status, chk = status_map[clean_dec], "x" if clean_dec == "approve" else " "
    line = (
        f"- [{chk}] **[GOVERNANCE DECISION: {mapped_status.upper()} by "
        f"`{actor_email or lid}` (`{lid}`)]** (`{clean_ref}`): {clean_reason}"
    )
    if not dry_run:
        append_tracker_line(ws, tracker, line, lid)
    ev = record_governance_event(
        ws, operation="record-decision", status=mapped_status, actor_email=actor_email,
        source_rel_path=clean_ref, dry_run=dry_run,
        reason_code=f"HUMAN_DECISION_{mapped_status.upper()}",
        message=f"{clean_ref}: {clean_reason}",
    )  # fmt: skip
    return {
        "workspace_dir": str(ws), "layer_id": lid, "item_ref": clean_ref, "decision": clean_dec,
        "status": mapped_status, "tracker": tracker, "dry_run": dry_run,
        "recorded_entry": line, "audit_event": ev,
    }  # fmt: skip


def summarize_work_orchestration_ledger(
    workspace_dir: Path, *, parent_dir: Path | None = None
) -> dict[str, Any]:
    """Summarize Node Work & Sprint Ledger trackers vs. 1-hop inter-layer task/proposal exchange."""
    ws, m = workspace_dir.resolve(), load_node_manifest(workspace_dir.resolve())
    ent_id = resolve_node_entity_identity(ws, m, parent_dir)
    chk_re = re.compile(r"^\s*-\s*\[([ xX/])\]\s+(.+)$")
    in_re = re.compile(r"(?:Delegated|Directive)\s+from\s+`[a-z0-9-]+`", re.IGNORECASE)
    out_re = re.compile(r"(?:\[[A-Z0-9-]+|Promote\b[^`]*)\s*->\s*`[a-z0-9-]+`")
    ex_toks = ("GOVERNANCE DECISION:", "Staged Governance Proposal")
    trk_sum: dict[str, dict[str, Any]] = {}
    own_tasks, in_dirs, out_delivs = list[str](), list[str](), list[str]()
    for trk in WORK_ORCHESTRATION_TRACKERS:
        fp = ws / trk
        lines = fp.read_text("utf-8").splitlines() if fp.is_file() else []
        items = [
            (mc.group(1).lower(), mc.group(2).strip()) for ln in lines if (mc := chk_re.match(ln))
        ]
        own = [
            (st, txt) for st, txt in items
            if not any(tok in txt for tok in ex_toks)
            and not in_re.search(txt) and not out_re.search(txt)
        ]  # fmt: skip
        if trk == "WORKTASK.md":
            own_tasks = [txt for st, txt in own if st in (" ", "/")]
        in_dirs.extend(txt for _st, txt in items if in_re.search(txt))
        out_delivs.extend(
            txt for st, txt in items if out_re.search(txt) or (st == "x" and in_re.search(txt))
        )
        trk_sum[trk] = {
            "exists": fp.is_file(), "open": sum(1 for st, _ in own if st == " "),
            "in_progress": sum(1 for st, _ in own if st == "/"),
            "completed": sum(1 for st, _ in own if st == "x"),
        }  # fmt: skip
    p_dir = ws / ".agents" / "proposals"
    props = (
        [str(p.relative_to(ws)).replace("\\", "/") for p in sorted(p_dir.rglob("*.md"))]
        if p_dir.is_dir()
        else []
    )
    return {
        "orchestration_contract": "zcg-work-ledger-v1", "node_id": ent_id["node_id"],
        "governing_root_id": ent_id["governing_root_id"],
        "own_node_ledger": {
            "trackers": trk_sum,
            "total_open_items": sum(v["open"] for v in trk_sum.values()),
            "total_in_progress_items": sum(v["in_progress"] for v in trk_sum.values()),
            "total_completed_items": sum(v["completed"] for v in trk_sum.values()),
            "active_node_tasks": own_tasks,
        },
        "inter_layer_exchange": {
            "scope_boundary": ent_id["exposure_boundary"], "inbound_directives": in_dirs,
            "inbound_proposals": props, "outbound_deliverables": out_delivs,
        },
    }  # fmt: skip
